<?php
/**
 * POST /api/humanize.php
 *
 * Хуманизация текста через Claude.
 *
 * Input:  { "text": "..." }
 * Output: { "text": "..." }
 */

require_once __DIR__ . '/helpers.php';

$input = getJsonInput();
requireFields($input, ['text']);

$text = $input['text'];

$systemPrompt = <<<'PROMPT'
Ты — мастер хуманизации текстов. Твоя задача — сделать текст максимально похожим на написанный живым человеком, а не AI.

Правила хуманизации:
1. Убери любую «роботизированность» — шаблонные фразы AI вроде «В современном мире», «Безусловно», «Стоит отметить», «Важно понимать»
2. Добавь естественные речевые обороты, свойственные живому автору
3. Варьируй длину предложений — чередуй короткие и длинные
4. Допускай лёгкую разговорность, где это уместно
5. Используй конкретные примеры вместо абстрактных рассуждений
6. Добавь авторскую позицию — «я считаю», «по моему опыту», «мне кажется»
7. Убери избыточную структурированность — не каждый абзац должен начинаться с вводного слова
8. Сохрани все факты, данные и основной смысл текста
9. НЕ меняй структуру (заголовки, подзаголовки) — только стиль и подачу
10. Финальный текст должен проходить проверку на AI-детекторах как «human-written»

Верни полный переработанный текст.
PROMPT;

$userMessage = "Хуманизируй следующий текст:\n\n{$text}";

$humanized = callClaude($systemPrompt, $userMessage);
sendJson(['text' => $humanized]);
