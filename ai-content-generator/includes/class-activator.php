    /**
     * Активация плагина.
     */
    public static function activate(): void {
        // API настройки
        $defaults = [
            'openrouter_api_key'  => '',
            'openrouter_base_url' => 'https://openrouter.ai/api/v1',
            'model_claude'        => 'anthropic/claude-sonnet-4-5-20250929',
            'model_gpt'           => 'openai/gpt-4o',
            'model_gemini'        => 'google/gemini-2.0-flash-001',
            'supadata_api_key'    => '',
            'supadata_base_url'   => 'https://api.supadata.ai/v1',
            'supadata_default_lang' => 'ru',
        ];

        foreach ($defaults as $key => $value) {
            if (get_option(AICG_OPTION_PREFIX . $key) === false) {
                add_option(AICG_OPTION_PREFIX . $key, $value);
            }
        }

        // Промпты
        $prompts = self::get_default_prompts();
        foreach ($prompts as $key => $value) {
            if (get_option(AICG_OPTION_PREFIX . 'prompt_' . $key) === false) {
                add_option(AICG_OPTION_PREFIX . 'prompt_' . $key, $value);
            }
        }
    }
